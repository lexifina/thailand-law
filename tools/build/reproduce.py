"""Generates corpus.json and REPRODUCE.md for the Thai law repository (called by build.py)."""
from __future__ import annotations

import hashlib
import json
import platform
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent


def _blob(path: Path) -> str:
    return subprocess.run(['git', 'hash-object', str(path)], capture_output=True, text=True).stdout.strip()


def _authority(built: list[dict]) -> str:
    """Section 29 of the Constitution, first paragraph, as the record holds it in force today."""
    for b in built:
        if b['act']['slug'] == 'constitution':
            text = b['states'][-1]['units']['s-029']['text']
            first = text.split('\n\n')[0]
            return f'รัฐธรรมนูญแห่งราชอาณาจักรไทย มาตรา 29 ("{first}")'
    raise SystemExit('no constitution')


def corpus_json(built: list[dict], today: str) -> str:
    days = [st['day'] for b in built for st in b['states']]
    c = {
        'corpus': 'th/national/acts',
        'name': 'Thai law: the Constitution of the Kingdom of Thailand B.E. 2560 (2017) and the Labour Protection Act '
                'B.E. 2541 (1998)',
        'label': 'Thailand',
        'language': 'th',
        'acts': [b['name'] for b in built],
        'history': 'in-force',
        'history_from': min(days),
        'record_to': max(d for d in days if d <= today),
        'built': today,
        'checked_on': today,
        'record_note': f'Checked against the Office of the Council of State (searchlaw.ocs.go.th) on {today}: every '
                       'consolidated text (ฉบับปรับปรุง) the OCS publishes for these two acts. One text (Labour '
                       'Protection Act, 2008-02-28) is rebuilt because the OCS consolidated that amendment out of '
                       'order; see README.',
        'in_force_trailer': 'In-force',
        'dates': {'commit': 'in-force', 'other_trailers': ['Promulgated'],
                  'time': '12:00 Asia/Bangkok (UTC+7, no summer time)'},
        'scope': {
            'trailer': 'Applies',
            'when_absent': 'this corpus records no scope notes (no commit carries Applies:); the absence is not a '
                           'statement that the change reaches every case',
            'default_reach': {
                'rule': 'no retroactive criminal liability or heavier punishment; otherwise an act applies from the '
                        'day it takes effect, as its own commencement section (มาตรา ๒) and transitional provisions '
                        '(บทเฉพาะกาล) set',
                'meaning': 'an amendment applies from its in-force day; how it treats earlier facts is set by the '
                           'amending act\'s transitional provisions, which this record reprints in the end/ files but '
                           'does not read as scope data',
                'authority': _authority(built),
                'decided_here': False,
            },
        },
        'tool': 'tools/thai.py',
        'citation': {
            'file': '([a-z-]+)/s-0*([0-9]+(?:-[0-9]+)?)\\.md',
            'cites': 'มาตรา ?{n}([^0-9/๐-๙]|$)',
            'n_format': 'thai-section: {n} is the section number in Thai digits, with /N for an inserted section: '
                        '83 -> ๘๓, 11-1 -> ๑๑/๑',
        },
        'has_future_branch': False,
    }
    return json.dumps(c, ensure_ascii=False, indent=2) + '\n'


def reproduce_md(built: list[dict], log: list[dict], ntags: int, requests: list[dict], today: str) -> str:
    scripts = ['build.py', 'ocs.py', 'parse.py', 'reproduce.py', 'check_repo.py', 'test_repo.py']
    ver = {}
    p = HERE / 'verification.json'
    if p.exists():
        ver = json.loads(p.read_text(encoding='utf-8'))
    data = hashlib.sha256()
    for b in built:
        for v in b['versions'] + b['amends']:
            data.update(v['sha256'].encode())
    n_req = len({json.dumps(r['body'], sort_keys=True) for r in requests})
    out = ['# How this repository was made', '',
           'Everything here is generated by the scripts in `tools/build/` from the data of one source. No AI wrote or',
           'edited legal text, and no model runs when the repository is built.', '',
           '## Source', '',
           '- The Office of the Council of State (สำนักงานคณะกรรมการกฤษฎีกา, OCS), law database',
           '  <https://searchlaw.ocs.go.th/council-of-state/>. The site is an app over a JSON API; the build calls',
           '  `POST https://searchlaw.ocs.go.th/ocs-api/public/doc/getLawDoc` (service `getPublicLawDoc`, body',
           '  `{"isTransEng": false, "timelineId": "<id>"}`), the call the site\'s own page makes, once per timeline.',
           f'- Retrieved {today}: {n_req} distinct requests (one persistent HTTPS connection, gzip, at most 4 at a time,',
           '  0.25 s apart), every answer cached gzip-compressed in the builder\'s `.cache/`.',
           '- The two seed timeline IDs (the current text of each act) were found with the public site\'s own search,',
           '  `POST https://www.ocs.go.th/searchlaw/indexs/list_table_search` (by title); every other ID comes from',
           '  the timeline list each document carries.',
           f'- sha256 over the per-document hashes, in build order: `{data.hexdigest()}`.', '',
           '## Terms and robots', '',
           '- `robots.txt`: none on www.ocs.go.th, ocs.go.th or searchlaw.ocs.go.th (each answers 404), checked',
           f'  {today}; no AI-crawler rules anywhere.',
           '- No terms of use are published on ocs.go.th (its policy pages cover privacy and data governance only).',
           '- Thai Copyright Act B.E. 2537 (1994), section 7: Acts, the Constitution and official texts of law are not',
           '  copyright works.',
           '- Not used: the Royal Gazette site (ratchakitcha.soc.go.th) answers every request, robots.txt included,',
           '  with a Cloudflare challenge, which we did not try to pass; law.go.th answers 403; krisdika.go.th no',
           '  longer answers. Gazette references here are the ones the OCS prints in its footnotes.', '',
           '## Commands, in order', '',
           '```',
           f'python -X utf8 scripts/thailand-law/build.py --today {today}            # fetch (cached) and build',
           'python -X utf8 scripts/thailand-law/check_repo.py                          # compare with the OCS texts',
           'python -X utf8 scripts/thailand-law/test_repo.py --record                  # reader smoke test',
           f'python -X utf8 scripts/thailand-law/build.py --offline --today {today} --verify-rebuild',
           f'python -X utf8 scripts/thailand-law/build.py --offline --today {today}  # final build from the cache',
           '```', '',
           '## Tools', '',
           f'- Python {platform.python_version()}, lxml, git {subprocess.run(["git", "--version"], capture_output=True, text=True).stdout.split()[-1]}.',
           '- Script blob hashes (git hash-object):']
    for s in scripts:
        if (HERE / s).exists():
            out.append(f'  - `{s}` {_blob(HERE / s)}')
    out += ['', '## Result', '',
            f'- {len(log)} law commits and 1 documentation commit; {ntags} tags.']
    if 'check' in ver:
        c = ver['check']
        out.append(f'- check_repo: {c["texts"]} texts ({c["files"]} files), {c["mismatches"]} mismatches; '
                   f'{c["wordcheck"]} texts word for word ({c["letters"]} letters), {c["word_mismatches"]} mismatches.')
    if 'rebuild' in ver:
        r = ver['rebuild']
        out.append(f'- Rebuild from the cache into an empty folder: identical = {str(r["identical"]).lower()} '
                   f'({r["commits"]} commits, {r["tags"]} tags).')
    if 'tests' in ver:
        t = ver['tests']
        out.append(f'- test_repo: {t["passed"]} of {t["total"]} passed.')
    out += ['', '## Decisions made by hand', '',
            '- The acts: the Constitution (the basic law) and the Labour Protection Act (amended nine times, with',
            '  clean point-in-time consolidations).',
            '- Where the OCS lists no amending act for a day, the change is credited to the instrument its',
            '  consolidation of that day newly reprints at the end (a royal decree, an NCPO order, the Act on Fines',
            '  by Administrative Penalty); each such commit says so and counts how many changed files name it.',
            '- Labour Protection Act, 2008: Act No. 3 (in force 2008-02-28) was consolidated after Act No. 2 (in',
            '  force 2008-05-27), so the OCS text dated 2008-02-28 also prints No. 2. The 2008-02-28 commit is the',
            '  2002 text plus only the files No. 3 changed (in section 5, which both change, only No. 3\'s paragraphs);',
            '  the 2008-05-27 commit is the OCS text dated 2008-02-28, which holds both. The OCS text dated',
            '  2008-05-27 lacks No. 3 and is not used.',
            '- Files that differ only in spacing (the OCS retyped them) are committed with the change of that day and',
            '  listed as `Respaced:`, not `Affecting:`.', '',
            '## What the AI did', '',
            'Claude Code with Claude Opus 5.5 (`claude-opus-5-5`) found the source and its API, checked robots.txt and',
            'terms, and wrote the scripts. It did not write or edit any legal text, commit message wording comes from',
            'templates in build.py, and no model runs at build time.', '']
    return '\n'.join(out)
